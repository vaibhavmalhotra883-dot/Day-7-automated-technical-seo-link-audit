nest_asyncio.apply()

# Configuration
START_URL = ""
BASE_DOMAIN = ""
ALLOWED_PATH_PREFIX = "/in/"  # Restricts crawl to the /in/ section. Change to "/" for the whole domain.
CONCURRENCY_LIMIT = 25        # Number of simultaneous requests (keeps it fast without crashing the server)
MAX_PAGES = 1500              # Safety cap to prevent infinite loops

visited_urls = set()
queue = asyncio.Queue()
page_data = {}
all_links_records = []

# Headers to mimic a real browser
HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
}

def normalize_url(url):
    """Removes fragments (#) and trailing slashes for clean comparison."""
    url, _ = urldefrag(url)
    return url.rstrip("/")

def is_valid_internal_url(url):
    """Checks if the URL belongs to the target domain and is a webpage (not an image/pdf)."""
    parsed = urlparse(url)
    if parsed.netloc != BASE_DOMAIN:
        return False
    if not parsed.path.startswith(ALLOWED_PATH_PREFIX.rstrip("/")):
        return False

    # Ignore non-HTML files
    ignored_extensions = ('.jpg', '.jpeg', '.png', '.gif', '.pdf', '.zip', '.css', '.js', '.svg', '.webp', '.mp4', '.xml')
    if parsed.path.lower().endswith(ignored_extensions):
        return False
    return True

async def fetch_and_parse(session, semaphore):
    while True:
        try:
            current_url = await asyncio.wait_for(queue.get(), timeout=3.0)
        except asyncio.TimeoutError:
            break

        if len(visited_urls) >= MAX_PAGES:
            queue.task_done()
            continue

        async with semaphore:
            try:
                async with session.get(current_url, headers=HEADERS, timeout=15) as response:
                    status_code = response.status
                    content_type = response.headers.get("Content-Type", "")

                    if "text/html" not in content_type:
                        queue.task_done()
                        continue

                    html = await response.text()
                    soup = BeautifulSoup(html, "html.parser")

                    # Extract Title and H1
                    title = soup.title.string.strip() if soup.title and soup.title.string else "No Title"
                    h1_tag = soup.find("h1")
                    h1 = h1_tag.get_text(strip=True) if h1_tag else "No H1"

                    internal_outlinks = []
                    external_outlinks = 0

                    # Extract all anchor tags
                    for a_tag in soup.find_all("a", href=True):
                        raw_href = a_tag["href"].strip()
                        if not raw_href or raw_href.startswith(("mailto:", "tel:", "javascript:")):
                            continue

                        full_url = normalize_url(urljoin(current_url + "/", raw_href))
                        anchor_text = a_tag.get_text(" ", strip=True) or "[Image/No Text]"
                        rel_attr = " ".join(a_tag.get("rel", [])) if a_tag.get("rel") else "dofollow"

                        parsed_target = urlparse(full_url)

                        if parsed_target.netloc == BASE_DOMAIN:
                            internal_outlinks.append(full_url)
                            all_links_records.append({
                                "Source URL": current_url,
                                "Target URL": full_url,
                                "Anchor Text": anchor_text,
                                "Link Type": rel_attr
                            })

                            # Add newly discovered internal URLs to the crawl queue
                            if is_valid_internal_url(full_url) and full_url not in visited_urls:
                                visited_urls.add(full_url)
                                await queue.put(full_url)
                        else:
                            external_outlinks += 1

                    # Store page summary
                    page_data[current_url] = {
                        "URL": current_url,
                        "Status Code": status_code,
                        "Page Title": title,
                        "H1 Tag": h1,
                        "Total Internal Outlinks": len(internal_outlinks),
                        "Unique Internal Outlinks": len(set(internal_outlinks)),
                        "External Outlinks": external_outlinks
                    }

                    if len(page_data) % 50 == 0:
                        print(f"Crawled {len(page_data)} pages...")

            except Exception as e:
                page_data[current_url] = {
                    "URL": current_url,
                    "Status Code": f"Error: {str(e)[:40]}",
                    "Page Title": "Failed to load",
                    "H1 Tag": "-",
                    "Total Internal Outlinks": 0,
                    "Unique Internal Outlinks": 0,
                    "External Outlinks": 0
                }
            finally:
                queue.task_done()

async def main():
    start_time = time.time()
    norm_start = normalize_url(START_URL)
    visited_urls.add(norm_start)
    await queue.put(norm_start)

    semaphore = asyncio.Semaphore(CONCURRENCY_LIMIT)
    connector = aiohttp.TCPConnector(limit=CONCURRENCY_LIMIT, ssl=False)

    print(f"Starting fast crawl on {START_URL}...")
    async with aiohttp.ClientSession(connector=connector) as session:
        tasks = [asyncio.create_task(fetch_and_parse(session, semaphore)) for _ in range(CONCURRENCY_LIMIT)]
        await queue.join()
        for task in tasks:
            task.cancel()

    elapsed = round(time.time() - start_time, 2)
    print(f"\nCrawl finished! Checked {len(page_data)} pages in {elapsed} seconds.")

    # Process data into DataFrames
    df_pages = pd.DataFrame(list(page_data.values()))
    df_links = pd.DataFrame(all_links_records)

    # Calculate Inbound Internal Links (Inlinks) per page
    if not df_links.empty:
        inlink_counts = df_links["Target URL"].value_counts().reset_index()
        inlink_counts.columns = ["URL", "Total Internal Inlinks"]

        unique_inlinks = df_links.drop_duplicates(subset=["Source URL", "Target URL"])["Target URL"].value_counts().reset_index()
        unique_inlinks.columns = ["URL", "Unique Referring Pages"]

        df_pages = pd.merge(df_pages, inlink_counts, on="URL", how="left")
        df_pages = pd.merge(df_pages, unique_inlinks, on="URL", how="left")
        df_pages["Total Internal Inlinks"] = df_pages["Total Internal Inlinks"].fillna(0).astype(int)
        df_pages["Unique Referring Pages"] = df_pages["Unique Referring Pages"].fillna(0).astype(int)
    else:
        df_pages["Total Internal Inlinks"] = 0
        df_pages["Unique Referring Pages"] = 0

    # Identify Potential Issues (Orphan/Low Inlink Pages & Broken Links)
    df_low_inlinks = df_pages[df_pages["Unique Referring Pages"] <= 1].sort_values(by="Unique Referring Pages")
    df_broken = df_pages[df_pages["Status Code"] != 200]

    # Save to a formatted Excel file
    output_filename = "MediaSearchGroup_Internal_Linking_Audit.xlsx"
    with pd.ExcelWriter(output_filename, engine="openpyxl") as writer:
        df_pages.to_excel(writer, sheet_name="Page Summary (All URLs)", index=False)
        df_low_inlinks.to_excel(writer, sheet_name="Low Inlinks & Orphans", index=False)
        df_broken.to_excel(writer, sheet_name="Broken or Error Pages", index=False)
        df_links.to_excel(writer, sheet_name="All Internal Links & Anchors", index=False)

    print(f"Generating Excel file: {output_filename}...")
    files.download(output_filename)

# Run the crawler
await main()